#!/usr/bin/env python3
"""Write the paper's per-system code listings (LaTeX) from results/code_snippets.json.

Each listing is a card: the system and function, a one-line note, then the original C above the
translated Rust, verbatim, with the artifact's own line numbers and the divergent lines highlighted.
The card links to the system's repository at the tested commit and to the exact C and Rust lines.
The text is real, selectable LaTeX (fancyvrb + Inconsolata), not an image. Macros are defined in the
paper's header.tex (snipcard, sniplabel, snipcodeC/R, ?snL*, ?snH*, ?snE, ?snT; command characters ? @ ").

    python3 scripts/make_snippet_listings.py --out out/figures   # writes snip-<system>.tex

<system> is the system's name in lower case, except FLOURINE, whose file is snip-fluorine.tex: the paper
inputs it under the tool's own spelling (\input{img/snip-fluorine}). Needs Pygments (pip install pygments)
for the syntax colouring.
"""
import argparse, json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FILE_KEY = {"FLOURINE": "fluorine"}   # file names the paper \inputs where they differ from the lower-cased system
MAXC = 66          # characters per code line that fit a 3.5 in column at the listing font size
TEX_ESC = {"\\": r"\textbackslash{}", "_": r"\_", "&": r"\&", "%": r"\%", "#": r"\#", "$": r"\$",
           "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}


def tex(s):
    return "".join(TEX_ESC.get(c, c) for c in s).replace("…", r"\dots{}").replace("²", r"\textsuperscript{2}") \
        .replace("·", r"\textperiodcentered{}")


def url(u):
    return u.replace("#", r"\#").replace("%", r"\%")


def colorize(text, side):
    """Syntax colouring with Pygments' C and Rust lexers, one line at a time (the excerpts are fragments).
    Each coloured token is wrapped in a macro defined in header.tex: ?skw (keyword), ?sty (type), ?snum
    (number), ?sstr (string, char), ?scom (comment), ?sfn (function name). The text itself is unchanged."""
    from pygments.lexers import CLexer, RustLexer
    from pygments.token import Comment, Keyword, Name, Number, String
    lexer = (CLexer if side == "c" else RustLexer)(stripnl=False, ensurenl=False)
    out = []
    for ttype, val in lexer.get_tokens(text):
        if not val or val.isspace():
            out.append(val); continue
        mac = ("sty" if ttype in Keyword.Type or ttype in Name.Builtin else
               "skw" if ttype in Keyword or ttype in Comment.Preproc else
               "snum" if ttype in Number else
               "sstr" if ttype in String else
               "scom" if ttype in Comment else
               "sfn" if ttype in Name.Function else None)
        out.append(f"?{mac}@{val}\"" if mac else val)
    s = "".join(out)
    assert s.replace("?skw@", "").replace("?sty@", "").replace("?snum@", "").replace("?sstr@", "") \
            .replace("?scom@", "").replace("?sfn@", "").replace("\"", "") == text, "colouring changed the text"
    return s


def code_lines(blk, side):
    out = []
    for l in blk["lines"]:
        if l["line"] is None:
            out.append("?snE@\"")
            continue
        t = l["text"]
        for ch in "?@\"":
            assert ch not in t, f"command character {ch!r} in code: {t!r}"
        cut = len(t) > MAXC
        t = t[:MAXC - 1] if cut else t
        out.append(("?snH" if l["hl"] else "?snL") + ("C" if side == "c" else "R") + f"@{l['line']}\""
                   + colorize(t, side) + ("?snT@\"" if cut else ""))
    return out


def card(s):
    title = tex(s["title"].replace(" · ", "|"))
    sysname, fn = title.split("|", 1)
    lines = [f"% Generated by scripts/make_snippet_listings.py from results/code_snippets.json; do not edit.",
             rf"\begin{{snipcard}}{{{sysname}}}{{{fn}}}{{{url(s['c']['source_url'])}}}",
             rf"\snipnote{{{tex(s['note'])}}}"]
    for side, lab in (("c", "C"), ("rust", "Rust")):
        blk = s[side]
        nums = [l["line"] for l in blk["lines"] if l["line"]]
        fname = tex(os.path.basename(blk["file"]))
        link = url(blk.get("url") or blk["source_url"])
        lines.append(rf"\sniplabel{{{lab}}}{{{fname}:{min(nums)}--{max(nums)}}}{{{link}}}")
        lines.append(r"\begin{snipcode" + ("C" if side == "c" else "R") + "}")
        lines += code_lines(blk, side)
        lines.append(r"\end{snipcode" + ("C" if side == "c" else "R") + "}")
    lines.append(r"\end{snipcard}")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--snippets", default=os.path.join(ROOT, "results/code_snippets.json"))
    ap.add_argument("--out", default=os.path.join(ROOT, "figures"))
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    for s in json.load(open(a.snippets))["snippets"]:
        key = FILE_KEY.get(s["system"], s["system"].lower().replace(" ", ""))
        p = os.path.join(a.out, f"snip-{key}.tex")
        open(p, "w").write(card(s))
        print("wrote", p)


if __name__ == "__main__":
    main()
